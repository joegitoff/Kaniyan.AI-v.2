NO_ALERT_TIPS = [
    "No rule was triggered with the current thresholds - conditions look within the configured ranges.",
    "Forecasts change; re-check before travel or outdoor events.",
]

GENERAL_DISCLAIMER = (
    "Kaniyan.AI is an educational project. Its alerts are generated by simple, illustrative rules "
    "on model forecast data. They are not official warnings and cannot predict local flooding."
)


def get_advice(variable_key: str, level: Level) -> list[str]:
    """Return the list of precautions for one variable at one level (empty list if unknown)."""
    return list(ADVICE.get(variable_key, {}).get(level, []))


def summarise_advice(alerts) -> list[str]:
    """Combine advice from all alerts, remove duplicates, keep order of severity."""
    if not alerts:
        return list(NO_ALERT_TIPS)
    seen, combined = set(), []
    for alert in sorted(alerts, key=lambda a: -int(a.level)):
        for tip in alert.advice:
            if tip not in seen:
                seen.add(tip)
                combined.append(tip)
    return combined
